/* ===================================================
   GK TRAVELS — CENTRAL WORKFLOW & INTEGRATION ENGINE
   Connects all modules, drives cascade effects,
   and provides global search.
   =================================================== */

window.GKWorkflow = {

  // ── LEAD CONVERSION ──────────────────────────────────
  // Converts a confirmed lead into Customer + Trip + Tasks + Reminders
  promoteLead(leadId) {
    const lead = window.GKData.leads.find(l => l.id === leadId);
    if (!lead) return null;
    if (lead.convertedTripId) {
      if (confirm('This lead has already been converted (Trip ' + lead.convertedTripId + '). Open that trip?')) {
        GKApp.openTrip(lead.convertedTripId);
      }
      return null;
    }

    // 1. Find or create customer
    let cust = window.GKData.customers.find(c => c.phone === lead.phone && lead.phone) ||
               window.GKData.customers.find(c => c.name.toLowerCase() === lead.name.toLowerCase());
    if (!cust) {
      cust = {
        id: window.GKData.nextCustomerId(),
        name: lead.name, phone: lead.phone || '', altPhone: '', email: lead.email || '',
        address: '', city: '',
        preferences: { seatPreference: '', mealPreference: '', hotelPreference: '', notes: '' },
        passportNo: '', passportExpiry: '', passportCountry: '',
        tripIds: [], bookingIds: [], documents: [],
        createdDate: new Date().toISOString().split('T')[0],
        sourceLeadId: leadId
      };
      window.GKData.customers.unshift(cust);
    }

    // 2. Create trip file
    const trip = {
      id:             window.GKData.nextTripId(),
      customer:       lead.name,
      phone:          lead.phone || '',
      email:          lead.email || '',
      customerId:     cust.id,
      pax:            lead.pax || 1,
      destination:    lead.destination || '',
      departure:      lead.travelDate || '',
      returnDate:     '',
      type:           'Leisure',
      status:         'confirmed',
      totalAmount:    lead.budget || 0,
      paidAmount:     0,
      balanceDue:     lead.budget || 0,
      gstRate:        5, gstAmount: 0, discount: 0,
      totalPayable:   lead.budget || 0,
      supplierCost:   0, grossProfit: 0, netProfit: 0, marginPct: 0,
      flightStatus:   'pending', hotelStatus:  'pending',
      visaStatus:     'pending', transferStatus:'pending',
      checkInStatus:  'not_due', voucherStatus: 'not_due',
      assignedTo:     lead.assignedTo || 'Priya Singh',
      createdDate:    new Date().toISOString().split('T')[0],
      notes:          lead.notes || '',
      sourceLeadId:   leadId,
      flights: [], hotels: [], activities: [], documents: [],
      timeline: [
        { date: new Date().toISOString().split('T')[0], event: 'Trip created from lead ' + leadId + ' — ' + lead.destination, type: 'done' }
      ]
    };
    window.GKData.trips.unshift(trip);

    // 3. Link trip to customer
    if (!cust.tripIds) cust.tripIds = [];
    cust.tripIds.push(trip.id);

    // 4. Update lead
    lead.status = 'confirmed';
    lead.convertedTripId = trip.id;
    lead.convertedCustomerId = cust.id;

    // 5. Auto-generate initial task checklist
    this._createInitialTasks(trip);

    // 6. Generate reminders if departure is set
    window.GKData.generateReminders(trip);

    window.GKData.save();
    GKApp.updateNotificationBadge();

    return { trip, customer: cust };
  },

  _createInitialTasks(trip) {
    const today = new Date().toISOString().split('T')[0];
    const dep   = trip.departure;
    const add = (title, category, priority, daysOffset) => {
      let dueDate = today;
      if (dep && daysOffset != null) {
        const d = new Date(dep); d.setDate(d.getDate() + daysOffset);
        dueDate = d.toISOString().split('T')[0];
      }
      window.GKData.tasks.unshift({
        id: window.GKData.nextTaskId(), title, tripId: trip.id,
        dueDate, priority, status: 'pending', category,
        notes: '', autoGenerated: true
      });
    };

    add('Book flights — ' + trip.destination, 'flights', 'urgent', 0);
    add('Book hotel — ' + trip.destination, 'hotel', 'urgent', 0);
    if (dep) {
      add('Collect advance payment from ' + trip.customer, 'payment', 'high', 0);
      add('Collect balance payment from ' + trip.customer, 'payment', 'high', -5);
      add('Send final documents to ' + trip.customer, 'documents', 'high', -2);
      add('Web check-in for ' + trip.customer, 'flights', 'urgent', -1);
    }
  },

  // ── BOOKING ADDED ────────────────────────────────────
  onBookingAdded(booking) {
    const today = new Date().toISOString().split('T')[0];

    // Link customer
    if (booking.customerId) {
      const cust = window.GKData.customers.find(c => c.id === booking.customerId);
      if (cust) {
        if (!cust.bookingIds) cust.bookingIds = [];
        if (!cust.bookingIds.includes(booking.id)) cust.bookingIds.push(booking.id);
      }
    } else if (booking.customerName) {
      // Auto-link by name/phone
      const cust = window.GKData.customers.find(c =>
        c.name.toLowerCase() === booking.customerName.toLowerCase() ||
        (booking.customerPhone && c.phone === booking.customerPhone)
      );
      if (cust) {
        booking.customerId = cust.id;
        if (!cust.bookingIds) cust.bookingIds = [];
        if (!cust.bookingIds.includes(booking.id)) cust.bookingIds.push(booking.id);
      }
    }

    // Update linked trip
    if (booking.refId) {
      const trip = window.GKData.trips.find(t => t.id === booking.refId);
      if (trip) {
        if (!trip.timeline) trip.timeline = [];
        trip.timeline.push({
          date: today,
          event: this._capitalize(booking.type) + ' booking added — ' + booking.id +
            (booking.customerName ? ' (' + booking.customerName + ')' : ''),
          type: 'done'
        });

        // Auto-create type-specific task
        this._createBookingTask(booking, trip);

        // Auto-add supplier payment record if cost is provided
        if (booking.supplierCost > 0) {
          const existing = window.GKData.payments.supplierPayments.find(p => p.bookingId === booking.id);
          if (!existing) {
            const supplierName = (booking.detail || {}).airline ||
              (booking.detail || {}).hotelName ||
              (booking.detail || {}).provider ||
              (booking.detail || {}).operatorName ||
              this._capitalize(booking.type) + ' Supplier';
            window.GKData.payments.supplierPayments.push({
              id: window.GKData.nextPayId('SP'),
              tripId: booking.refId, bookingId: booking.id,
              supplier: supplierName,
              description: this._capitalize(booking.type) + ' — ' + booking.customerName,
              amount: booking.supplierCost,
              dueDate: '', status: 'pending',
              paidDate: null
            });
          }
        }

        // Recalc trip finance
        window.GKData.calcTripFinance(trip);

        // Regenerate trip reminders
        window.GKData.generateReminders(trip);
      }
    }

    // Standalone booking reminders
    window.GKData.generateBookingReminders(booking);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  _createBookingTask(booking, trip) {
    const today = new Date().toISOString().split('T')[0];
    const tasks = [];
    if (booking.type === 'flight' && booking.status === 'pending') {
      const d = booking.detail || {};
      tasks.push({ title: 'Issue ticket — ' + (d.airline || '') + ' ' + (d.flightNumber || '') + ' for ' + trip.customer, category: 'flights', priority: 'urgent' });
    }
    if (booking.type === 'hotel' && booking.status === 'pending') {
      tasks.push({ title: 'Confirm hotel — ' + ((booking.detail || {}).hotelName || '') + ' for ' + trip.customer, category: 'hotel', priority: 'high' });
    }
    if (booking.type === 'visa') {
      tasks.push({ title: 'Collect visa documents — ' + ((booking.detail || {}).country || '') + ' for ' + trip.customer, category: 'visa', priority: 'high' });
    }
    if (booking.type === 'insurance' && booking.status === 'pending') {
      tasks.push({ title: 'Issue insurance policy for ' + trip.customer, category: 'other', priority: 'medium' });
    }
    if (booking.type === 'cab' && booking.status === 'pending') {
      tasks.push({ title: 'Assign driver/cab for ' + trip.customer + ' — ' + ((booking.detail || {}).pickupLocation || ''), category: 'transfer', priority: 'high' });
    }

    tasks.forEach(t => {
      window.GKData.tasks.unshift({
        id: window.GKData.nextTaskId(), title: t.title,
        tripId: trip.id, bookingId: booking.id,
        dueDate: today, priority: t.priority,
        status: 'pending', category: t.category,
        notes: '', autoGenerated: true
      });
    });
  },

  // ── BOOKING FINANCE SAVED ────────────────────────────
  onBookingFinanceSaved(bookingId) {
    const b = window.GKData.bookings.find(x => x.id === bookingId);
    if (!b) return;
    if (!b.timeline) b.timeline = [];
    b.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Finance updated — ₹' + (b.sellingPrice || 0), type: 'done' });

    // Add/update supplier payment record
    if (b.supplierCost > 0 && b.refId) {
      const existing = window.GKData.payments.supplierPayments.find(p => p.bookingId === bookingId);
      if (existing) {
        existing.amount = b.supplierCost;
      } else {
        const supplierName = (b.detail || {}).airline || (b.detail || {}).hotelName ||
          (b.detail || {}).provider || this._capitalize(b.type) + ' Supplier';
        window.GKData.payments.supplierPayments.push({
          id: window.GKData.nextPayId('SP'),
          tripId: b.refId, bookingId,
          supplier: supplierName,
          description: this._capitalize(b.type) + ' — ' + b.customerName,
          amount: b.supplierCost, dueDate: '', status: 'pending', paidDate: null
        });
      }
    }

    // Recalc linked trip
    if (b.refId) {
      const trip = window.GKData.trips.find(t => t.id === b.refId);
      if (trip) window.GKData.calcTripFinance(trip);
    }

    // Generate reminders for balance due
    window.GKData.generateBookingReminders(b);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── PAYMENT RECORDED ─────────────────────────────────
  onPaymentRecorded(tripId) {
    const trip = window.GKData.trips.find(t => t.id === tripId);
    if (!trip) return;

    // Recalculate paid amount from payment records
    const totalPaid = window.GKData.payments.customerPayments
      .filter(p => p.tripId === tripId && p.status === 'received')
      .reduce((s, p) => s + p.amount, 0);
    trip.paidAmount = totalPaid;
    trip.balanceDue = Math.max(0, (trip.totalPayable || trip.totalAmount || 0) - totalPaid);
    window.GKData.calcTripFinance(trip);

    const lastPay = window.GKData.payments.customerPayments
      .filter(p => p.tripId === tripId && p.status === 'received')
      .slice(-1)[0];
    if (!trip.timeline) trip.timeline = [];
    trip.timeline.push({
      date: new Date().toISOString().split('T')[0],
      event: 'Payment received — ₹' + (lastPay ? lastPay.amount : 0) + ' via ' + (lastPay ? lastPay.method : ''),
      type: 'done'
    });

    // Auto-complete payment tasks if balance cleared
    if (trip.balanceDue === 0) {
      window.GKData.tasks
        .filter(t => t.tripId === tripId && t.category === 'payment' && t.status !== 'completed')
        .forEach(t => { t.status = 'completed'; });
      trip.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Trip fully paid — balance cleared', type: 'done' });
    }

    // Regenerate reminders (balance reminders may now clear)
    window.GKData.generateReminders(trip);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── HOTEL PAID ───────────────────────────────────────
  onHotelPaid(tripId) {
    const trip = window.GKData.trips.find(t => t.id === tripId);
    if (!trip) return;
    if (!trip.timeline) trip.timeline = [];
    trip.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Hotel payment marked paid', type: 'done' });
    // Auto-complete hotel tasks
    window.GKData.tasks
      .filter(t => t.tripId === tripId && t.category === 'hotel' && t.status !== 'completed')
      .forEach(t => { t.status = 'completed'; });
    window.GKData.calcTripFinance(trip);
    window.GKData.generateReminders(trip);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── SUPPLIER PAID ────────────────────────────────────
  onSupplierPaid(payId) {
    const pay = window.GKData.payments.supplierPayments.find(p => p.id === payId);
    if (!pay) return;
    const trip = window.GKData.trips.find(t => t.id === pay.tripId);
    if (trip) {
      if (!trip.timeline) trip.timeline = [];
      trip.timeline.push({
        date: new Date().toISOString().split('T')[0],
        event: 'Supplier paid — ' + pay.supplier + ' ₹' + pay.amount,
        type: 'done'
      });
      window.GKData.calcTripFinance(trip);
    }
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── VISA STATUS CHANGED ──────────────────────────────
  onVisaStatusChanged(tripId, newStatus) {
    const trip = window.GKData.trips.find(t => t.id === tripId);
    if (!trip) return;
    const statusLabels = {
      na: 'Visa N/A', pending: 'Visa pending applied',
      submitted: 'Visa submitted to consulate',
      approved: 'Visa APPROVED', rejected: 'Visa REJECTED'
    };
    if (!trip.timeline) trip.timeline = [];
    trip.timeline.push({
      date: new Date().toISOString().split('T')[0],
      event: statusLabels[newStatus] || ('Visa status: ' + newStatus),
      type: newStatus === 'approved' ? 'done' : newStatus === 'rejected' ? 'urgent' : 'pending'
    });
    // Auto-complete visa tasks if approved
    if (newStatus === 'approved') {
      window.GKData.tasks
        .filter(t => t.tripId === tripId && t.category === 'visa' && t.status !== 'completed')
        .forEach(t => { t.status = 'completed'; });
    }
    // Link visa status change to customer timeline
    if (trip.customerId) {
      const cust = window.GKData.customers.find(c => c.id === trip.customerId);
      if (cust) {
        if (!cust.timeline) cust.timeline = [];
        cust.timeline.push({ date: new Date().toISOString().split('T')[0], event: statusLabels[newStatus] + ' — ' + trip.destination, type: 'done' });
      }
    }
    window.GKData.generateReminders(trip);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── CHECK-IN DONE ────────────────────────────────────
  onCheckInDone(tripId) {
    const trip = window.GKData.trips.find(t => t.id === tripId);
    if (!trip) return;
    if (!trip.timeline) trip.timeline = [];
    trip.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Web check-in completed for ' + trip.customer, type: 'done' });
    // Auto-complete check-in tasks
    window.GKData.tasks
      .filter(t => t.tripId === tripId && (t.title.toLowerCase().includes('check-in') || t.category === 'flights') && t.status !== 'completed')
      .forEach(t => { t.status = 'completed'; });
    window.GKData.generateReminders(trip);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── DOCUMENT CROSS-LINKING ───────────────────────────
  onDocumentUploaded(docObj, entityType, entityId) {
    // If uploaded to a booking, also link to its trip and customer
    if (entityType === 'booking') {
      const booking = window.GKData.bookings.find(b => b.id === entityId);
      if (booking) {
        if (booking.refId) {
          const trip = window.GKData.trips.find(t => t.id === booking.refId);
          if (trip && !trip.documents.find(d => d.id === docObj.id)) {
            trip.documents.push({ ...docObj, linkedFrom: 'booking:' + entityId });
          }
        }
        const custId = booking.customerId;
        if (custId) {
          const cust = window.GKData.customers.find(c => c.id === custId);
          if (cust && !cust.documents.find(d => d.id === docObj.id)) {
            cust.documents.push({ ...docObj, linkedFrom: 'booking:' + entityId });
          }
        }
        if (!booking.timeline) booking.timeline = [];
        booking.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Document uploaded: ' + docObj.name, type: 'done' });
      }
    }
    // If uploaded to a trip, also link to customer
    if (entityType === 'trip') {
      const trip = window.GKData.trips.find(t => t.id === entityId);
      if (trip && trip.customerId) {
        const cust = window.GKData.customers.find(c => c.id === trip.customerId);
        if (cust && !cust.documents.find(d => d.id === docObj.id)) {
          cust.documents.push({ ...docObj, linkedFrom: 'trip:' + entityId });
        }
      }
      if (trip) {
        if (!trip.timeline) trip.timeline = [];
        trip.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Document uploaded: ' + docObj.name, type: 'done' });
      }
    }
    window.GKData.save();
  },

  // ── BOOKING STATUS ADVANCED ──────────────────────────
  onBookingStatusChanged(bookingId, newStatus) {
    const b = window.GKData.bookings.find(x => x.id === bookingId);
    if (!b) return;
    if (!b.timeline) b.timeline = [];
    b.timeline.push({ date: new Date().toISOString().split('T')[0], event: 'Status → ' + newStatus.replace(/_/g, ' '), type: newStatus === 'completed' || newStatus === 'approved' || newStatus === 'ticketed' ? 'done' : newStatus === 'cancelled' || newStatus === 'rejected' ? 'urgent' : 'pending' });

    // If flight becomes ticketed, auto-complete ticket-issue task
    if (b.type === 'flight' && newStatus === 'ticketed' && b.refId) {
      window.GKData.tasks
        .filter(t => t.tripId === b.refId && t.category === 'flights' && t.title.toLowerCase().includes('issue ticket') && t.status !== 'completed')
        .forEach(t => { t.status = 'completed'; });
    }

    // Push status change to linked trip timeline
    if (b.refId) {
      const trip = window.GKData.trips.find(t => t.id === b.refId);
      if (trip) {
        if (!trip.timeline) trip.timeline = [];
        trip.timeline.push({ date: new Date().toISOString().split('T')[0], event: this._capitalize(b.type) + ' (' + b.id + ') → ' + newStatus.replace(/_/g, ' '), type: newStatus === 'completed' || newStatus === 'ticketed' || newStatus === 'approved' ? 'done' : 'pending' });
      }
    }

    window.GKData.generateBookingReminders(b);
    window.GKData.save();
    GKApp.updateNotificationBadge();
  },

  // ── HELPER ───────────────────────────────────────────
  _capitalize(s) { return s ? s.charAt(0).toUpperCase() + s.slice(1) : ''; }
};

/* ===================================================
   GK SEARCH — Global smart search across all modules
   =================================================== */
window.GKSearch = {
  show(term) {
    const results = this.query(term);
    let box = document.getElementById('gk-search-results');
    if (!box) {
      box = document.createElement('div');
      box.id = 'gk-search-results';
      box.className = 'absolute top-full left-0 right-0 mt-1 bg-white border border-gray-200 rounded-xl shadow-2xl z-50 overflow-hidden';
      const wrapper = document.getElementById('gk-search-wrapper');
      if (wrapper) wrapper.appendChild(box);
    }

    if (!term || term.length < 2 || results.length === 0) {
      box.innerHTML = term && term.length >= 2
        ? '<div class="px-4 py-3 text-sm text-gray-500">No results for "' + this._esc(term) + '"</div>'
        : '';
      box.classList.toggle('hidden', !term || term.length < 2 || results.length === 0);
      return;
    }

    const iconMap = { trip:'map', booking:'ticket', customer:'contact', lead:'user-plus', flight:'plane' };
    const colorMap = { trip:'text-blue-500', booking:'text-purple-500', customer:'text-green-500', lead:'text-yellow-500', flight:'text-accent' };
    box.innerHTML = results.map((r, i) => `
<div class="flex items-center gap-3 px-4 py-2.5 hover:bg-gray-50 cursor-pointer border-b border-gray-100 last:border-0 transition-colors" onclick="GKSearch.navigate(${i})">
  <div class="w-7 h-7 rounded-lg bg-gray-100 flex items-center justify-center flex-shrink-0">
    <i data-lucide="${iconMap[r.type] || 'file'}" class="w-3.5 h-3.5 ${colorMap[r.type] || 'text-gray-500'}"></i>
  </div>
  <div class="flex-1 min-w-0">
    <div class="text-sm font-medium text-gray-900 truncate">${this._esc(r.title)}</div>
    <div class="text-xs text-gray-500 truncate">${this._esc(r.subtitle)}</div>
  </div>
  <span class="text-xs px-1.5 py-0.5 rounded bg-gray-100 text-gray-500 capitalize flex-shrink-0">${r.type}</span>
</div>`).join('');
    box.classList.remove('hidden');
    this._lastResults = results;
    if (window.lucide) setTimeout(() => lucide.createIcons(), 0);
  },

  navigate(index) {
    const r = (this._lastResults || [])[index];
    if (!r) return;
    this.close();
    const input = document.getElementById('gk-search-input');
    if (input) input.value = '';
    r.action();
  },

  close() {
    const box = document.getElementById('gk-search-results');
    if (box) box.classList.add('hidden');
  },

  query(term) {
    if (!term || term.length < 2) return [];
    const q = term.toLowerCase().trim();
    const results = [];

    // Trips
    window.GKData.trips.forEach(t => {
      if ((t.id || '').toLowerCase().includes(q) ||
          (t.customer || '').toLowerCase().includes(q) ||
          (t.destination || '').toLowerCase().includes(q) ||
          (t.phone || '').replace(/\s/g,'').includes(q.replace(/\s/g,''))) {
        results.push({
          type: 'trip', id: t.id,
          title: t.customer,
          subtitle: t.destination + ' · ' + t.id + (t.departure ? ' · ' + t.departure : ''),
          action: () => GKApp.openTrip(t.id)
        });
      }
      // PNR search within trip flights
      (t.flights || []).forEach(f => {
        if ((f.pnr || '').toLowerCase().includes(q) || (f.number || '').toLowerCase().includes(q)) {
          results.push({
            type: 'flight', id: t.id,
            title: (f.airline || '') + ' ' + (f.number || '') + ' — PNR: ' + (f.pnr || ''),
            subtitle: t.customer + ' · ' + t.id,
            action: () => GKApp.openTrip(t.id)
          });
        }
      });
    });

    // Bookings
    window.GKData.bookings.forEach(b => {
      const d = b.detail || {};
      if ((b.id || '').toLowerCase().includes(q) ||
          (b.customerName || '').toLowerCase().includes(q) ||
          (d.pnr || '').toLowerCase().includes(q) ||
          (d.confirmationNo || '').toLowerCase().includes(q) ||
          (d.hotelName || '').toLowerCase().includes(q) ||
          (d.flightNumber || '').toLowerCase().includes(q) ||
          (d.policyNo || '').toLowerCase().includes(q)) {
        results.push({
          type: 'booking', id: b.id,
          title: b.customerName + ' — ' + (b.type || ''),
          subtitle: b.id + (d.pnr ? ' · PNR: ' + d.pnr : '') + (d.hotelName ? ' · ' + d.hotelName : ''),
          action: () => GKApp.openBooking(b.id)
        });
      }
    });

    // Customers
    window.GKData.customers.forEach(c => {
      if ((c.id || '').toLowerCase().includes(q) ||
          (c.name || '').toLowerCase().includes(q) ||
          (c.phone || '').replace(/\s/g,'').includes(q.replace(/\s/g,'')) ||
          (c.passportNo || '').toLowerCase().includes(q) ||
          (c.email || '').toLowerCase().includes(q)) {
        results.push({
          type: 'customer', id: c.id,
          title: c.name,
          subtitle: 'Customer · ' + (c.phone || '') + (c.passportNo ? ' · ' + c.passportNo : ''),
          action: () => GKApp.openCustomer(c.id)
        });
      }
    });

    // Leads
    window.GKData.leads.forEach(l => {
      if ((l.id || '').toLowerCase().includes(q) ||
          (l.name || '').toLowerCase().includes(q) ||
          (l.phone || '').replace(/\s/g,'').includes(q.replace(/\s/g,'')) ||
          (l.destination || '').toLowerCase().includes(q)) {
        results.push({
          type: 'lead', id: l.id,
          title: l.name,
          subtitle: 'Lead · ' + l.destination + ' · ' + l.id,
          action: () => { GKApp.navigate('leads'); setTimeout(() => window.LeadsModule && window.LeadsModule.showLeadDetail(l.id), 80); }
        });
      }
    });

    return results.slice(0, 10);
  },

  _esc(s) { return String(s || '').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); },
  _lastResults: []
};
